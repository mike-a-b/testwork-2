-- 1. Изменение движка MyISAM → InnoDB
use testdatabase;
ALTER TABLE info ENGINE=InnoDB;
ALTER TABLE data ENGINE=InnoDB;
ALTER TABLE link ENGINE=InnoDB;

-- 2. Переименование зарезервированных колонок
ALTER TABLE info CHANGE `desc` description TEXT;
ALTER TABLE data CHANGE `date` data_date DATE;

-- 3. Изменение кодировки на utf8mb4
ALTER TABLE info CONVERT TO CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
ALTER TABLE data CONVERT TO CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
ALTER TABLE link CONVERT TO CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;

-- 4. Добавление составного первичного ключа в связующей таблице
ALTER TABLE link
    ADD PRIMARY KEY (data_id, info_id);

-- 5. Добавление внешних ключей (при условии, что данные соответствуют)
ALTER TABLE link
    ADD CONSTRAINT fk_link_data
        FOREIGN KEY (data_id) REFERENCES data(id)
            ON DELETE CASCADE ON UPDATE CASCADE;

ALTER TABLE link
    ADD CONSTRAINT fk_link_info
        FOREIGN KEY (info_id) REFERENCES info(id)
            ON DELETE CASCADE ON UPDATE CASCADE;

-- 6. Индексация (если внешние ключи не создают автоматом)
ALTER TABLE link
    ADD INDEX idx_info_id (info_id),
    ADD INDEX idx_data_id (data_id);
